import {MobileDeviceIcon} from '@sanity/icons'
import {defineField, defineType} from 'sanity'

export default defineType({
  name: 'app',
  title: 'Application',
  type: 'document',
  icon: MobileDeviceIcon,
  groups: [
    {name: 'overview', title: 'Overview', default: true},
    {name: 'media', title: 'Media'},
    {name: 'pricing', title: 'Pricing'},
    {name: 'details', title: 'App Details'},
    {name: 'publishing', title: 'Publishing'},
  ],
  fields: [
    defineField({
      name: 'title',
      title: 'App Title',
      type: 'string',
      group: 'overview',
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'slug',
      title: 'Slug',
      type: 'slug',
      group: 'overview',
      options: {source: 'title', maxLength: 96},
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'description',
      title: 'Short Description',
      type: 'text',
      group: 'overview',
      rows: 3,
      description: 'Shown on the App Store listing card.',
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'category',
      title: 'Category',
      type: 'reference',
      group: 'overview',
      to: [{type: 'category'}],
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'mainImage',
      title: 'Main Image',
      type: 'image',
      group: 'media',
      options: {hotspot: true},
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'screenshots',
      title: 'Screenshots',
      type: 'array',
      group: 'media',
      of: [{type: 'image', options: {hotspot: true}}],
      options: {layout: 'grid'},
      description: 'Additional screenshots shown on the app detail page.',
    }),
    defineField({
      name: 'content',
      title: 'Detailed Content',
      type: 'blockContent',
      group: 'details',
    }),
    defineField({
      name: 'price',
      title: 'Price (USD)',
      type: 'number',
      group: 'pricing',
      validation: (Rule) => Rule.required().min(0),
    }),
    defineField({
      name: 'isFree',
      title: 'Free App',
      type: 'boolean',
      group: 'pricing',
      initialValue: false,
      description: 'When enabled, the app is shown as FREE regardless of price.',
    }),
    defineField({
      name: 'appType',
      title: 'App Type',
      type: 'string',
      group: 'details',
      options: {
        list: [
          {title: 'Web Application', value: 'web'},
          {title: 'Mobile App (APK)', value: 'mobile'},
          {title: 'Desktop Application', value: 'desktop'},
          {title: 'Plugin / Extension', value: 'plugin'},
        ],
      },
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'downloadUrl',
      title: 'Download URL',
      type: 'url',
      group: 'details',
      description: 'Direct link to Google Drive, Dropbox, or other file host.',
    }),
    defineField({
      name: 'fileSize',
      title: 'File Size (MB)',
      type: 'number',
      group: 'details',
    }),
    defineField({
      name: 'version',
      title: 'Version',
      type: 'string',
      group: 'details',
    }),
    defineField({
      name: 'systemRequirements',
      title: 'System Requirements',
      type: 'text',
      group: 'details',
      rows: 3,
    }),
    defineField({
      name: 'features',
      title: 'Key Features',
      type: 'array',
      group: 'details',
      of: [{type: 'string'}],
    }),
    defineField({
      name: 'tags',
      title: 'Tags',
      type: 'array',
      group: 'details',
      of: [{type: 'string'}],
      options: {layout: 'tags'},
    }),
    defineField({
      name: 'publishedAt',
      title: 'Published At',
      type: 'datetime',
      group: 'publishing',
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'isActive',
      title: 'Visible in Store',
      type: 'boolean',
      group: 'publishing',
      initialValue: true,
      description: 'Turn off to hide this app from the public store.',
    }),
    defineField({
      name: 'author',
      title: 'Author',
      type: 'reference',
      group: 'publishing',
      to: [{type: 'author'}],
    }),
    defineField({
      name: 'downloadCount',
      title: 'Download Count',
      type: 'number',
      group: 'publishing',
      initialValue: 0,
      readOnly: true,
    }),
    defineField({
      name: 'rating',
      title: 'Rating (0–5)',
      type: 'number',
      group: 'publishing',
      initialValue: 0,
      validation: (Rule) => Rule.min(0).max(5),
    }),
  ],
  preview: {
    select: {
      title: 'title',
      author: 'author.name',
      media: 'mainImage',
      price: 'price',
      isFree: 'isFree',
      isActive: 'isActive',
    },
    prepare({title, author, media, price, isFree, isActive}) {
      const priceLabel = isFree ? 'Free' : `$${price ?? 0}`
      const status = isActive === false ? 'Hidden' : 'Active'
      return {
        title: title || 'Untitled App',
        subtitle: `${priceLabel} • ${status}${author ? ` • ${author}` : ''}`,
        media,
      }
    },
  },
})
